class User(Base):
    __tablename__ = "users"

    id = Column(Integer, primary_key=True, index=True)
    phone_number = Column(String, unique=True, index=True, nullable=False)
    full_name = Column(String, nullable=True)
    role = Column(String, default="customer")  # "customer" or "worker"
    dob = Column(String, nullable=True)
    gender = Column(String, nullable=True)
    offered_services = Column(String, nullable=True)  # JSON list or comma-separated string of subCategory IDs
    availability = Column(String, nullable=True)      # JSON string: {"days_off": [...], "dead_slots": [...]}
    referral_code = Column(String(6), unique=True, index=True, nullable=True)
    referral_points = Column(Integer, default=0, nullable=False)
    referral_earnings = Column(Integer, default=0, nullable=False)
    is_online = Column(Integer, default=1, nullable=False)
    # Permanent block / deactivate flag: 1 = blocked (hidden from marketplace, login denied).
    is_blocked = Column(Integer, default=0, nullable=False)
    # Worker approval flow: "pending" (in review) | "approved" | "rejected".
    # Customers are always "approved". Defaults to "approved" so existing rows stay live.
    verification_status = Column(String(20), default="approved", nullable=False)
    # Public R2 URL of the worker profile photo (nullable until uploaded).
    profile_photo = Column(String(1000), nullable=True)
    # Price edit permission (feature/marketing #1): 0 = locked by default,
    # admin must explicitly allow a worker to set own prices.
    price_edit_allowed = Column(Integer, default=0, nullable=False)
    created_at = Column(DateTime(timezone=True), server_default=func.now())


