class Booking(Base):
    __tablename__ = "bookings"

    id = Column(Integer, primary_key=True, index=True)
    customer_id = Column(Integer, ForeignKey("users.id"), nullable=False)
    worker_id = Column(Integer, ForeignKey("users.id"), nullable=False)
    service_id = Column(String(50), nullable=False)
    date = Column(String(10), nullable=False)       # YYYY-MM-DD
    time_slot = Column(String(20), nullable=False)  # e.g. "14:00-15:00"
    status = Column(String(20), default="pending")  # pending | accepted | in_progress | completed | cancelled
    address = Column(String, nullable=True)
    amount = Column(String(20), nullable=True)       # price string e.g. "299"
    discount_code = Column(String(50), nullable=True)  # applied discount code
    discount_amount = Column(String(20), nullable=True)  # Rs saved e.g. "50"
    # Customer online payments + platform fee (feature/payment):
    # amount = base service price after discount; platform_fee = slab fee;
    # total_amount = base + fee (what Razorpay charges for online mode).
    platform_fee = Column(String(20), nullable=True)      # Rs fee e.g. "30"
    total_amount = Column(String(20), nullable=True)      # Rs total e.g. "329"
    payment_mode = Column(String(20), default="cash")     # cash | online
    payment_status = Column(String(20), default="cash")   # cash | awaiting_online | paid_online | failed
    razorpay_order_id = Column(String(100), nullable=True, index=True)
    # Kazilen admin confirmation (feature/marketing #2): 0 = awaiting Kazilen,
    # 1 = confirmed (auto when booking_config.auto_confirm=1).
    admin_confirmed = Column(Integer, default=1, nullable=False)
    start_otp = Column(String(6), nullable=True)    # generated by worker at job site to start
    end_otp = Column(String(6), nullable=True)      # generated by worker to close job
    otp = Column(String(6), nullable=True)          # legacy, kept for migration compat
    created_at = Column(DateTime(timezone=True), server_default=func.now())
    updated_at = Column(DateTime(timezone=True), onupdate=func.now(), nullable=True)


